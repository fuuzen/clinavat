// Refreshes the bundled model price snapshot from LiteLLM, so cost estimates never fetch prices at run time.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { litellmPrices } from '../src/token-usage/prices.js';

const source = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const target = fileURLToPath(new URL('../src/token-usage/model-prices.ts', import.meta.url));

const response = await fetch(source);
if (!response.ok) throw new Error(`Price list request failed: ${response.status}`);
const entries = Object.entries(litellmPrices(await response.json()))
  .map(([name, price]) => `  ${JSON.stringify(name)}: [${price.map(value => String(value)).join(', ')}],`);
await writeFile(target, `// Generated by \`npm run prices:update -w backend\` from LiteLLM's model price list; do not edit by hand.
import type { ModelPrice } from './prices.js';

export const priceSnapshotDate = '${new Date().toISOString().slice(0, 10)}';

/** USD per million tokens: input, cache read, cache write, output. */
export const modelPrices: Record<string, ModelPrice> = {
${entries.join('\n')}
};
`);
console.log(`Wrote ${entries.length} model prices to ${target}`);
