// Refreshes the bundled model price snapshot from LiteLLM, so cost estimates never fetch prices at run time.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const source = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const target = fileURLToPath(new URL('../src/token-usage/model-prices.ts', import.meta.url));
const perMillion = value => typeof value === 'number' ? Number((value * 1e6).toPrecision(12)) : null;

const response = await fetch(source);
if (!response.ok) throw new Error(`Price list request failed: ${response.status}`);
const models = await response.json();
const entries = Object.entries(models).filter(([name, model]) => model && typeof model === 'object'
  && ['openai', 'anthropic'].includes(model.litellm_provider) && ['chat', 'responses'].includes(model.mode)
  && /^(gpt-|o\d|claude-|codex)/.test(name) && !name.includes('/')
  && typeof model.input_cost_per_token === 'number' && typeof model.output_cost_per_token === 'number')
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([name, model]) => `  ${JSON.stringify(name)}: [${[model.input_cost_per_token, model.cache_read_input_token_cost,
    model.cache_creation_input_token_cost, model.output_cost_per_token].map(value => String(perMillion(value))).join(', ')}],`);
await writeFile(target, `// Generated by \`npm run prices:update -w backend\` from LiteLLM's model price list; do not edit by hand.
export const priceSnapshotDate = '${new Date().toISOString().slice(0, 10)}';

/** USD per million tokens: input, cache read, cache write, output. */
export const modelPrices: Record<string, readonly [number, number | null, number | null, number]> = {
${entries.join('\n')}
};
`);
console.log(`Wrote ${entries.length} model prices to ${target}`);
